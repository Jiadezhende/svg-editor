import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';

const ROOT = fileURLToPath(new URL('..', import.meta.url));

/** 以脚本回放方式运行真实入口（stdin 为管道，即非 TTY）。 */
function runCli(script: string): string[] {
  const proc = spawnSync(process.execPath, ['--import', 'tsx', 'src/main.ts'], {
    cwd: ROOT,
    input: script,
    encoding: 'utf8',
  });
  expect(proc.stderr).toBe('');
  expect(proc.status).toBe(0);
  return proc.stdout.replace(/\n$/, '').split('\n');
}

describe('main 入口（脚本回放）', () => {
  it('help 列出全部命令及语法（canvas 两种形式各占一行）', () => {
    const lines = runCli('help\n');
    expect(lines.slice(0, 2)).toEqual(["svg-editor 0.1 — type 'help' for commands", 'svg> help']);
    expect([...lines.slice(2)].sort()).toEqual(
      [
        'init [w] [h]',
        'read <file.svg>',
        'save [file.svg]',
        'canvas',
        'canvas <w> <h>',
        'create <type> <id> [params…] [in <containerId>]',
        'delete <id>',
        'move <id> <dx> <dy>',
        'scale <id> <factor>',
        'set <id> <attr> <value>',
        'group <newGid> <id1> <id2>…',
        'ungroup <gid>',
        'addto <gid> <id>',
        'front <id>',
        'back <id>',
        'tree [id]',
        'show <id>',
        'help',
        'undo',
        'redo',
        'exit',
        'quit',
      ].sort(),
    );
  });

  it('占位命令与未知命令报错不同；exit 后进程正常结束', () => {
    expect(runCli('front r1\nfoo\nexit\nhelp\n')).toEqual([
      "svg-editor 0.1 — type 'help' for commands",
      'svg> front r1',
      'error: command not implemented yet: front',
      'svg> foo',
      'error: unknown command: foo',
      'svg> exit',
    ]);
  });

  it('文档生命周期与画布：无文档、init、覆盖警告、查看与修改尺寸', () => {
    const script = [
      'canvas',
      'canvas a 0',
      'init 400',
      'init a 600',
      'init 0 600',
      'init',
      'init 100.5 200',
      'canvas 1024 768',
      'canvas 0 600',
      'canvas',
    ];
    expect(runCli(script.join('\n') + '\n').slice(1)).toEqual([
      'svg> canvas',
      "error: no document. use 'init' or 'read' first",
      'svg> canvas a 0',
      'error: not a number: a',
      'svg> init 400',
      'error: wrong number of arguments. usage: init [w] [h]',
      'svg> init a 600',
      'error: not a number: a',
      'svg> init 0 600',
      'error: canvas size must be positive',
      'svg> init',
      'canvas 800x600 created',
      'svg> init 100.5 200',
      'warning: previous document discarded',
      'canvas 100.5x200 created',
      'svg> canvas 1024 768',
      'canvas resized to 1024x768',
      'svg> canvas 0 600',
      'error: canvas size must be positive',
      'svg> canvas',
      'canvas 1024x768',
    ]);
  });

  it('撤销与重做：空栈、文档类命令后禁止与解禁、canvas 两种形式', () => {
    const script = [
      'undo',
      'redo',
      'init',
      'undo',
      'create g markers',
      'create circle c1 100 100 20 red in markers',
      'create rect box 10 10 50 50 in markers',
      'canvas',
      'delete markers',
      'tree',
      'undo',
      'tree',
      'redo',
      'undo',
      'undo',
      'undo',
      'undo',
      'tree',
      'redo',
      'canvas 1024 768',
      'undo',
      'redo',
      'create rect r1 0 0 1 1',
      'create rect r1 0 0 1 1',
      'undo',
      'undo',
      'canvas 400',
      'canvas a b',
    ];
    expect(runCli(script.join('\n') + '\n').slice(1)).toEqual([
      'svg> undo',
      'error: nothing to undo',
      'svg> redo',
      'error: nothing to redo',
      'svg> init',
      'canvas 800x600 created',
      'svg> undo',
      'error: undo not allowed after io command',
      'svg> create g markers',
      'g#markers created',
      'svg> create circle c1 100 100 20 red in markers',
      'circle#c1 created in g#markers',
      'svg> create rect box 10 10 50 50 in markers',
      'rect#box created in g#markers',
      'svg> canvas',
      'canvas 800x600',
      'svg> delete markers',
      'g#markers deleted',
      'svg> tree',
      'svg (800x600)',
      'svg> undo',
      'g#markers restored into svg',
      'svg> tree',
      'svg (800x600)',
      '└── g#markers',
      '    ├── circle#c1  cx=100 cy=100 r=20',
      '    └── rect#box  x=10 y=10 width=50 height=50',
      'svg> redo',
      'g#markers deleted',
      'svg> undo',
      'g#markers restored into svg',
      'svg> undo',
      'rect#box removed',
      'svg> undo',
      'circle#c1 removed',
      'svg> undo',
      'g#markers removed',
      'svg> tree',
      'svg (800x600)',
      'svg> redo',
      'g#markers created',
      'svg> canvas 1024 768',
      'canvas resized to 1024x768',
      'svg> undo',
      'error: undo not allowed after io command',
      'svg> redo',
      'error: redo not allowed after io command',
      'svg> create rect r1 0 0 1 1',
      'rect#r1 created',
      'svg> create rect r1 0 0 1 1',
      'error: id already exists: r1',
      'svg> undo',
      'rect#r1 removed',
      'svg> undo',
      'error: nothing to undo',
      'svg> canvas 400',
      'error: wrong number of arguments. usage: canvas <w> <h>',
      'svg> canvas a b',
      'error: not a number: a',
    ]);
  });

  it('显示：tree 全文档与子树、show 明细、删除后结构随之变化', () => {
    const script = [
      'tree',
      'init',
      'tree',
      'create rect bg 0 0 800 600 #ffffff',
      'create text title 20 40 "My Diagram"',
      'create g markers',
      'create circle c1 100 100 20 red in markers',
      'create rect box 200 80 60 60 #3366ff in markers',
      'tree',
      'tree markers',
      'show c1',
      'show title',
      'show markers',
      'show r9',
      'delete box',
      'tree markers',
    ];
    expect(runCli(script.join('\n') + '\n').slice(1)).toEqual([
      'svg> tree',
      "error: no document. use 'init' or 'read' first",
      'svg> init',
      'canvas 800x600 created',
      'svg> tree',
      'svg (800x600)',
      'svg> create rect bg 0 0 800 600 #ffffff',
      'rect#bg created',
      'svg> create text title 20 40 "My Diagram"',
      'text#title created',
      'svg> create g markers',
      'g#markers created',
      'svg> create circle c1 100 100 20 red in markers',
      'circle#c1 created in g#markers',
      'svg> create rect box 200 80 60 60 #3366ff in markers',
      'rect#box created in g#markers',
      'svg> tree',
      'svg (800x600)',
      '├── rect#bg  x=0 y=0 width=800 height=600',
      '├── text#title  x=20 y=40 text="My Diagram"',
      '└── g#markers',
      '    ├── circle#c1  cx=100 cy=100 r=20',
      '    └── rect#box  x=200 y=80 width=60 height=60',
      'svg> tree markers',
      'g#markers',
      '├── circle#c1  cx=100 cy=100 r=20',
      '└── rect#box  x=200 y=80 width=60 height=60',
      'svg> show c1',
      'circle#c1  parent=g#markers',
      '  cx=100 cy=100 r=20',
      '  fill=red',
      'svg> show title',
      'text#title  parent=svg',
      '  x=20 y=40 text="My Diagram"',
      'svg> show markers',
      'g#markers  parent=svg',
      '  children=2',
      'svg> show r9',
      'error: no such shape: r9',
      'svg> delete box',
      'rect#box deleted',
      'svg> tree markers',
      'g#markers',
      '└── circle#c1  cx=100 cy=100 r=20',
    ]);
  });

  it('图形创建与删除：in 子句、各类报错、容器连同子孙删除', () => {
    const script = [
      'create rect r1 0 0 10 10',
      'init',
      'create rect r1 10 20 100 50 #eee',
      'create text t1 20 40 "My Diagram"',
      'create g node1',
      'create rect start 120 100 160 60 #4a90d9 in node1',
      'create text start-label 155 135 "开始" in node1',
      'create rect 1abc 0 0 1 1',
      'create rect r1 0 0 1 1',
      'create circle c1 0 0 -5',
      'create rect r2 0 0 1 1 in node9',
      'create rect r2 0 0 1 1 in start',
      'create rect r2 0 0 10 10 in',
      'create rect r2 a 0 1 1',
      'create hexagon h1',
      'create box n1 0 0 10 10 "t"',
      'delete node1',
      'delete start',
      'delete r9',
      'create g node1',
    ];
    expect(runCli(script.join('\n') + '\n').slice(1)).toEqual([
      'svg> create rect r1 0 0 10 10',
      "error: no document. use 'init' or 'read' first",
      'svg> init',
      'canvas 800x600 created',
      'svg> create rect r1 10 20 100 50 #eee',
      'rect#r1 created',
      'svg> create text t1 20 40 "My Diagram"',
      'text#t1 created',
      'svg> create g node1',
      'g#node1 created',
      'svg> create rect start 120 100 160 60 #4a90d9 in node1',
      'rect#start created in g#node1',
      'svg> create text start-label 155 135 "开始" in node1',
      'text#start-label created in g#node1',
      'svg> create rect 1abc 0 0 1 1',
      'error: invalid id: 1abc',
      'svg> create rect r1 0 0 1 1',
      'error: id already exists: r1',
      'svg> create circle c1 0 0 -5',
      'error: r must be non-negative',
      'svg> create rect r2 0 0 1 1 in node9',
      'error: no such container: node9',
      'svg> create rect r2 0 0 1 1 in start',
      'error: not a container: start',
      'svg> create rect r2 0 0 10 10 in',
      'error: wrong number of arguments. usage: create rect <id> <x> <y> <width> <height> [fill] [in <containerId>]',
      'svg> create rect r2 a 0 1 1',
      'error: not a number: a',
      'svg> create hexagon h1',
      'error: unknown shape type: hexagon (is the plugin loaded?)',
      'svg> create box n1 0 0 10 10 "t"',
      'error: unknown shape type: box (is the plugin loaded?)',
      'svg> delete node1',
      'g#node1 deleted',
      'svg> delete start',
      'error: no such shape: start',
      'svg> delete r9',
      'error: no such shape: r9',
      'svg> create g node1',
      'g#node1 created',
    ]);
  });

  it('CRLF 换行的脚本与 LF 结果一致', () => {
    expect(runCli('# c\r\nquit\r\n')).toEqual(["svg-editor 0.1 — type 'help' for commands", 'svg> # c', 'svg> quit']);
  });
});
